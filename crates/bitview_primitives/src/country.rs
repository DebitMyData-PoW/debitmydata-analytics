//! A pool's country, as DebitMyData's pool list writes it: two letters ("US") or the country's name in
//! English ("Turkey", "United Arab Emirates"), read as its ISO 3166-1 alpha-2 code.

/// A country, from its code or its name in English (its letters and digits only, any case or
/// accents); none for text that names no country.
pub fn country_code(text: &str) -> Option<String> {
    let text = text.trim();
    if text.len() == 2 && text.bytes().all(|b| b.is_ascii_alphabetic()) {
        return Some(text.to_ascii_uppercase());
    }
    let key = text
        .chars()
        .filter(char::is_ascii_alphanumeric)
        .map(|c| c.to_ascii_lowercase())
        .collect::<String>();
    NAMES
        .binary_search_by(|(name, _)| (*name).cmp(key.as_str()))
        .ok()
        .map(|i| NAMES[i].1.to_owned())
}

